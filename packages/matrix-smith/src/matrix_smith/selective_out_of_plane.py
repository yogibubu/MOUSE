"""Compose ORACLE SOOP displacements in a frozen molecular reference frame.

This opt-in local chart keeps displacement generators distinct from Gaussian
U/H covectors. It is not substituted into a global curvilinear B matrix.
When combined with ring directions the dual is computed for the complete
displacement set, preserving the specified atomic supports.
"""

from dataclasses import dataclass
import numpy as np
from matrix_chem.soop_contract import (
    expected_soop_support_keys, soop_support_key, validate_soop_primitives,
)


def _reactive_soop_bonds(contract):
    return {
        tuple(sorted((candidate.atoms[0], atom)))
        for candidate in getattr(contract, "primitive_candidates", ())
        if candidate.function == "U"
        and candidate.family == "OUT_OF_PLANE"
        and candidate.domain_id == "PRIMARY_TOPOLOGY::REACTIVE_SUPPORT"
        and len(candidate.atoms) == 4
        for atom in candidate.atoms[1:]
    }


@dataclass(frozen=True)
class SoopCombination:
    name: str
    center_atom: int
    primitive_ids: tuple[str, ...]
    coefficients: tuple[float, ...]
    moving_atoms: tuple[int, ...]


@dataclass(frozen=True)
class SelectiveOutOfPlanePlan:
    combinations: tuple[SoopCombination, ...]
    excluded_endocyclic_ids: tuple[str, ...]
    singular_ids: tuple[str, ...]
    ring_representation: str
    displacements: np.ndarray  # (3N, number of combinations), unit columns
    excluded_exocyclic_ring_ids: tuple[str, ...] = ()


def build_selective_out_of_plane_plan(contract, *, ring_representation):
    """Average terminal non-ring SOOPs; a separate ring basis owns ring motions.

    Acyclic centers average all three oriented primitives. One external
    substituent remains strictly single-atom. The normalized oriented mean
    uses 1/sqrt(k), since the k single-atom displacement columns are orthogonal.
    This is geometric normalization, not an assumption of equivalent ligands.
    """
    representation = str(ring_representation).lower()
    if representation not in {"flap", "triangular_flap", "charm", "local_out_of_plane", "soop"}:
        raise ValueError("SOOP plan requires an explicitly supplied complete ring representation")
    records = contract.selective_out_of_plane_primitives
    reactive_bonds = _reactive_soop_bonds(contract)
    validate_soop_primitives(
        records,
        contract.primary_topology,
        auxiliary_bonds=reactive_bonds,
    )
    # An old contract must be regenerated by ORACLE; SMITH never perceives missing SOOPs.
    adjacency = {a: set() for a in range(1, contract.primary_topology.natoms + 1)}
    for a, b in contract.primary_topology.bonds:
        adjacency[a].add(b)
        adjacency[b].add(a)
    for a, b in reactive_bonds:
        adjacency[a].add(b)
        adjacency[b].add(a)
    expected = expected_soop_support_keys(contract.primary_topology)
    if not expected.issubset({soop_support_key(p) for p in records}):
        raise ValueError("incomplete SOOP contract: regenerate the primitives with ORACLE")
    groups = {}
    excluded_endocyclic, excluded_exocyclic_ring, singular = [], [], []
    for p in records:
        if p.endocyclic:
            excluded_endocyclic.append(p.identifier)
        elif p.moving_atom_ring_ids:
            # The bond is exocyclic even if the moving atom belongs to a
            # different ring. Its ring motion is not a terminal umbrella.
            excluded_exocyclic_ring.append(p.identifier)
        elif len(adjacency[p.moving_atom]) == 1:
            groups.setdefault(p.center_atom, []).append(p)
        if p.status != "REGULAR":
            singular.append(p.identifier)
    columns, combinations = [], []
    for center, primitives in sorted(groups.items()):
        if any(p.status != "REGULAR" for p in primitives):
            # Do not silently turn a three-ligand umbrella into a partial mean.
            raise ValueError(f"SOOP center {center} has a singular exocyclic reference plane")
        k = len(primitives)
        coefficient = 1.0 / np.sqrt(k)
        columns.append(sum((p.displacement(contract.primary_topology.natoms).ravel()
                            for p in primitives)) * coefficient)
        combinations.append(SoopCombination(
            name=f"{'SOOP' if k == 1 else 'UMBRELLA'}_C{center:06d}",
            center_atom=center,
            primitive_ids=tuple(p.identifier for p in primitives),
            coefficients=(coefficient,) * k,
            moving_atoms=tuple(p.moving_atom for p in primitives),
        ))
    directions = np.column_stack(columns) if columns else np.zeros((3 * contract.primary_topology.natoms, 0))
    directions.setflags(write=False)
    return SelectiveOutOfPlanePlan(
        tuple(combinations), tuple(excluded_endocyclic), tuple(singular),
        representation, directions, tuple(excluded_exocyclic_ring),
    )


@dataclass(frozen=True)
class RingSoopPlan:
    """Ring displacements made only from ORACLE endocyclic SOOP primitives."""
    names: tuple[str, ...]
    primitive_ids: tuple[str, ...]
    coefficients: np.ndarray  # primitive x ring-coordinate
    displacements: np.ndarray


def build_ring_soop_displacements(
    contract,
    coordinates_angstrom,
    *,
    target_rank=None,
    complete_pool=False,
):
    """Build cyclic Fourier puckering combinations of selective displacements.

    For each ordered n-ring, first combine the two endocyclic SOOPs belonging
    to each center-ring pair, then form the n-3 cyclic harmonics over those
    centers. Only atoms of that same ring enter the first-stage combination.
    A shared fused-ring edge may participate in both of its rings. No U/H
    primitive is evaluated. This is a frozen local displacement basis, not a
    nonlinear moving-plane coordinate.
    """
    xyz = np.asarray(coordinates_angstrom, dtype=float)
    topology = contract.primary_topology
    if xyz.shape != (topology.natoms, 3) or not np.isfinite(xyz).all():
        raise ValueError("invalid ring SOOP reference geometry")
    records = contract.selective_out_of_plane_primitives
    validate_soop_primitives(
        records,
        topology,
        auxiliary_bonds=_reactive_soop_bonds(contract),
    )
    regular = tuple(p for p in records if p.status == "REGULAR" and p.endocyclic_ring_ids)
    primitives = np.column_stack([p.displacement(topology.natoms).ravel() for p in regular]) if regular else np.zeros((xyz.size, 0))
    # A three-membered ring has no independent puckering harmonic (n-3=0),
    # but its endocyclic SOOP sources can still replace local angular rows.
    # Keep that source pool when the mixed definition requests completion.
    if target_rank == 0 and not complete_pool:
        empty = np.zeros((len(regular), 0))
        directions = np.zeros((xyz.size, 0))
        empty.setflags(write=False)
        directions.setflags(write=False)
        return RingSoopPlan((), tuple(p.identifier for p in regular), empty, directions)
    columns, names = [], []
    center_ring_columns, center_ring_names = [], []
    for ring_id, ring in enumerate(topology.rings, 1):
        n = len(ring)
        if n <= 3:
            continue
        r = xyz[np.array(ring)-1]
        area = np.cross(r-r.mean(0), np.roll(r,-1,axis=0)-r.mean(0)).sum(0)
        if np.linalg.norm(area) < 1e-10:
            raise ValueError("ring SOOP has an undefined oriented mean plane")
        area /= np.linalg.norm(area)
        # First form one strictly ring-local contribution for every center.
        # In a simple trigonal ring this combines the two SOOPs associated
        # with its two endocyclic bonds.  At a fused center the shared-bond
        # SOOP belongs to both center-ring groups, while each nonshared bond
        # remains confined to its own ring.
        center_coefficients = np.zeros((len(regular), n))
        ring_indices_by_center = [
            [
                i
                for i, primitive in enumerate(regular)
                if primitive.center_atom == center
                and ring_id in primitive.endocyclic_ring_ids
            ]
            for center in ring
        ]
        # Centers with fewer than three neighbors have no oriented SOOP plane.
        # Their ring chart is supplied by the separate flap/CHARM family.
        if any(not indices for indices in ring_indices_by_center):
            continue
        for j, center in enumerate(ring):
            indices = ring_indices_by_center[j]
            for i in indices:
                alignment = np.dot(regular[i].normal, area)
                if abs(alignment) < 1e-10:
                    raise ValueError("ring SOOP normal cannot be oriented against the ring plane")
                center_coefficients[i, j] = np.sign(alignment) / np.sqrt(len(indices))
            motion = primitives @ center_coefficients[:, j]
            norm = np.linalg.norm(motion)
            if norm < 1e-10:
                raise ValueError("center-ring SOOP combination is singular")
            center_coefficients[:, j] /= norm
            center_ring_columns.append(center_coefficients[:, j].copy())
            center_ring_names.append(
                f"SOOP_RING{ring_id:04d}_CENTER{center:06d}"
            )
        angles = 2*np.pi*np.arange(n)/n
        harmonics = []
        for order in range(2, (n+1)//2):
            harmonics += [np.sqrt(2/n)*np.cos(order*angles),
                          np.sqrt(2/n)*np.sin(order*angles)]
        if n % 2 == 0:
            harmonics += [(-1.)**np.arange(n)/np.sqrt(n)]
        assert len(harmonics) == n-3
        for index, harmonic in enumerate(harmonics, 1):
            columns.append(center_coefficients @ harmonic)
            names.append(f"SOOP_RING{ring_id:04d}_PUCKER{index:02d}")
    # Fused and bridged cycles can make per-ring harmonics dependent. Reduce
    # them jointly, then complete the requested cyclic rank from the same
    # ring-local center combinations. No cross-ring average and no U/H
    # coordinate is used in this closure.
    required = len(columns) if target_rank is None else int(target_rank)
    candidates = [*columns, *center_ring_columns]
    candidate_names = [*names, *center_ring_names]
    if complete_pool:
        # Face harmonics are a compact starting chart, but in a noncoplanar
        # cage they need not span every symmetry-allowed local puckering mode.
        # Complete only with ORACLE's face-owned selective primitives.
        candidates.extend(np.eye(len(regular))[:, index] for index in range(len(regular)))
        candidate_names.extend(p.identifier for p in regular)
        coefficients = (
            np.column_stack(candidates)
            if candidates
            else np.zeros((len(regular), 0))
        )
        directions = primitives @ coefficients
        for array in (coefficients, directions):
            array.setflags(write=False)
        return RingSoopPlan(
            tuple(candidate_names),
            tuple(p.identifier for p in regular),
            coefficients,
            directions,
        )
    selected, selected_names = [], []
    current = np.zeros((xyz.size,0))
    for coefficient, name in zip(candidates,candidate_names,strict=True):
        trial = np.column_stack((current,primitives@coefficient))
        if np.linalg.matrix_rank(trial,tol=1e-10) > current.shape[1]:
            selected.append(coefficient)
            selected_names.append(name)
            current = trial
        if len(selected) == required:
            break
    if len(selected) != required:
        raise ValueError(f"endocyclic SOOP pool spans {len(selected)}/{required} required ring motions")
    coefficients = np.column_stack(selected) if selected else np.zeros((len(regular),0))
    directions = primitives @ coefficients
    for array in (coefficients, directions):
        array.setflags(write=False)
    return RingSoopPlan(tuple(selected_names), tuple(p.identifier for p in regular), coefficients, directions)


@dataclass(frozen=True)
class FrozenSoopChart:
    """Exact linear chart of the supplied displacements, in the fixed frame.

    x=x0+Dq; B is the dual pseudoinverse, B'=0.  These derivatives belong to
    this linear chart only.  Neither re-centering nor reorientation is implicit.
    Values off the represented affine subspace are rejected.
    """

    reference_coordinates_angstrom: np.ndarray
    directions: np.ndarray
    b_matrix: np.ndarray
    names: tuple[str, ...]

    def geometry(self, values):
        q = np.asarray(values, dtype=float)
        if q.shape != (self.directions.shape[1],) or not np.isfinite(q).all():
            raise ValueError("invalid SOOP chart amplitudes")
        return self.reference_coordinates_angstrom + (self.directions @ q).reshape((-1, 3))

    def b_derivative(self):
        """Exact analytic B' for this frozen linear chart (coordinate, x, x)."""
        return np.zeros((len(self.names), self.directions.shape[0], self.directions.shape[0]))

    def values(self, coordinates_angstrom, *, atol=1e-10):
        xyz = np.asarray(coordinates_angstrom, dtype=float)
        if xyz.shape != self.reference_coordinates_angstrom.shape or not np.isfinite(xyz).all():
            raise ValueError("invalid SOOP chart geometry")
        delta = (xyz - self.reference_coordinates_angstrom).ravel()
        q = self.b_matrix @ delta
        if np.linalg.norm(delta - self.directions @ q) > atol:
            raise ValueError("geometry lies outside the frozen SOOP displacement subspace")
        return q

    def transform_derivatives(self, gradient, hessian=None):
        """Transform analytic derivatives expressed per angstrom (and angstrom²).

        Energy units are unchanged. Callers with atomic-unit Cartesian
        derivatives must convert their length units before this operation.
        No finite-difference derivative is evaluated here.
        """
        g = np.asarray(gradient, dtype=float).reshape(-1)
        if g.shape != (self.directions.shape[0],) or not np.isfinite(g).all():
            raise ValueError("invalid Cartesian gradient for SOOP chart")
        gq = self.directions.T @ g
        if hessian is None:
            return gq
        h = np.asarray(hessian, dtype=float)
        if h.shape != (g.size, g.size) or not np.isfinite(h).all() or not np.allclose(h, h.T):
            raise ValueError("invalid Cartesian Hessian for SOOP chart")
        # x(q) is affine; its second derivative is exactly zero even when g != 0.
        return gq, self.directions.T @ h @ self.directions


def bind_selective_out_of_plane_chart(plan, coordinates_angstrom, *,
                                      ring_directions=None, ring_names=()):
    """Bind the local SOOP chart, optionally with already constructed ring motions.

    Ring columns must leave the designated external atoms fixed. This explicit
    check prevents a pseudoinverse of a mobile-plane U from masquerading as a
    selective displacement. Full optimization-chart integration is separate.
    """
    xyz = np.asarray(coordinates_angstrom, dtype=float)
    if xyz.shape != (plan.displacements.shape[0] // 3, 3) or not np.isfinite(xyz).all():
        raise ValueError("invalid reference geometry for SOOP plan")
    columns = plan.displacements
    names = tuple(c.name for c in plan.combinations)
    if ring_directions is not None:
        ring = np.asarray(ring_directions, dtype=float)
        if ring.ndim != 2 or ring.shape[0] != xyz.size or ring.shape[1] != len(ring_names):
            raise ValueError("invalid ring displacement matrix or names")
        for c in plan.combinations:
            for atom in c.moving_atoms:
                if np.any(np.abs(ring[3*(atom-1):3*atom]) > 1e-12):
                    raise ValueError(f"ring direction moves SOOP substituent atom {atom}")
        columns = np.column_stack((ring, columns))
        names = tuple(ring_names) + names
    if not np.isfinite(columns).all():
        raise ValueError("nonfinite SOOP displacement matrix")
    singular = np.linalg.svd(columns, compute_uv=False)
    if columns.shape[1] > columns.shape[0] or (len(singular) and singular[-1] <= 1e-10 * singular[0]):
        raise ValueError("dependent SOOP/ring displacements; do not duplicate inversion directions")
    directions = columns.copy()
    dual = np.linalg.pinv(directions, rcond=1e-10)
    reference = xyz.copy()
    for array in (directions, dual, reference):
        array.setflags(write=False)
    return FrozenSoopChart(reference, directions, dual, names)


def selective_out_of_plane_from_xyzin(path, *, ring_representation):
    """Public ORACLE -> SMITH entry point for SOOP displacement experiments."""
    from matrix_chem import read_oracle_sonic_contract, read_enriched_xyz
    contract = read_oracle_sonic_contract(path)
    plan = build_selective_out_of_plane_plan(contract, ring_representation=ring_representation)
    xyz = np.asarray(read_enriched_xyz(path).coordinates_angstrom, dtype=float)
    # Check that the frozen local frame really belongs to this reference geometry.
    for p in contract.selective_out_of_plane_primitives:
        if not np.allclose(xyz[p.moving_atom-1], p.reference_position_angstrom, atol=1e-12, rtol=0):
            raise ValueError("SOOP reference geometry changed: regenerate the ORACLE contract")
        if p.status == "REGULAR":
            c, a, b = (i-1 for i in p.plane_atoms)
            normal = np.cross(xyz[a]-xyz[c], xyz[b]-xyz[c])
            if np.linalg.norm(normal) <= 1e-14 or not np.allclose(normal / np.linalg.norm(normal), p.normal, atol=1e-10, rtol=0):
                raise ValueError("SOOP reference plane changed: regenerate the ORACLE contract")
    if str(ring_representation).lower() == "soop":
        rings = build_ring_soop_displacements(contract, xyz)
        return plan, bind_selective_out_of_plane_chart(plan, xyz,
            ring_directions=rings.displacements, ring_names=rings.names)
    return plan, bind_selective_out_of_plane_chart(plan, xyz)
